// FeatureGlobe
//
// Astrocartography globe visualization module for CartoStar iOS
//
// This package provides:
// - Mapbox Maps SDK with globe projection (3D Earth rendering)
// - Astrocartography line rendering (MC, IC, ASC, DSC)
// - Interactive location selection and line inspection
// - Integration with AstroCore for astronomical calculations
// - Duo (compatibility) mode for couples analysis
//
// IMPORTANT: Mapbox Access Token Setup
// ------------------------------------
// Add your Mapbox access token to Info.plist:
//   <key>MBXAccessToken</key>
//   <string>YOUR_MAPBOX_ACCESS_TOKEN</string>
//
// Or configure it programmatically before using MapboxGlobeView:
//   MapboxOptions.accessToken = "YOUR_TOKEN"
